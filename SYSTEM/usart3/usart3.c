void USART3_IRQHandler(void)                    //串口3中断服务程序
{
    if(USART_GetITStatus(USART3, USART_IT_RXNE) != RESET)           // 空闲中断
    {
        MotorSpeed_Re_Date[MotorSpeed_Re_Count] = USART_ReceiveData(USART3);
        MotorSpeed_Re_Count++;
        if(MotorSpeed_Re_Date[0] == 0xAA)
        {
            if(MotorSpeed_Re_Count > 9)
            {
                int receivedCRC = (MotorSpeed_Re_Date[9] << 8) | MotorSpeed_Re_Date[8];
                int expectedCRC = crc16(MotorSpeed_Re_Date, 8);
                if(expectedCRC == receivedCRC) {
                    MotorSpeed_Re_Count = 0;
                    MotorSpeed_Re_Flag = 1;
                } else {
                    MotorSpeed_Re_Count = 0;
                    MotorSpeed_Re_Flag = 0;
                }
            }
        }
        else
        {
            MotorSpeed_Re_Count = 0;
        }
        USART_ClearITPendingBit(USART3, USART_IT_RXNE);
    }
    if(USART_GetITStatus(USART3, USART_IT_TXE) == SET)
    {
        USART_ClearITPendingBit(USART3, USART_IT_TXE);
    }
}

int8_t ReturnReviseFlag;
void WheelReturnedDataHandle(void)
{
    if(MotorSpeed_Re_Flag == 1)
    {
        ReturnedWheelData[MotorSpeed_Re_Date[1]].ReturnedWheelSpeedValue = (MotorSpeed_Re_Date[6] << 8) | MotorSpeed_Re_Date[7];
        ReturnedWheelData[MotorSpeed_Re_Date[1]].ReturnedWheelErrorCode = MotorSpeed_Re_Date[5];

        if(MotorSpeed_Re_Date[1] == 1 || MotorSpeed_Re_Date[1] == 2 || MotorSpeed_Re_Date[1] == 3)
        {
            ReturnReviseFlag = -1;
        }
        else
        {
            ReturnReviseFlag = 1;
        }
        ReturnedWheelData[MotorSpeed_Re_Date[1]].ReturnedWheelHallCnt += (ReturnedWheelData[MotorSpeed_Re_Date[1]].ReturnedWheelSpeedValue* ReturnReviseFlag / 2);
        MotorSpeed_Re_Flag = 0;
    }
}
