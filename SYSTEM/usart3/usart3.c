////////*16位CRC校验函数查表法*////////////////
u16 crc16(u8* puchMsg, u8 usDataLen)
{
    u8 uchCRCHi = 0xFF ;
    u8 uchCRCLo = 0xFF ;
    u16 uIndex ;
    while(usDataLen--)
    {
        uIndex = uchCRCHi ^ * puchMsg++ ;
        uchCRCHi = uchCRCLo^ auchCRCHi[uIndex] ;
        uchCRCLo = auchCRCLo[uIndex] ;
    }
    return (((u8)(uchCRCLo) << 8) | uchCRCHi) ;
}
/**********************************************
串口配置函数
RS485通信控制电机
配置了串口3，PD8 PD9
115200,8b，1，N
接收中断使能
无发送
**********************************************/
void USART3_Init(u32 bound)
{
    GPIO_InitTypeDef gpio_initstructure;
    USART_InitTypeDef usart_initstructure;
    //USART_ClockInitTypeDef usart_clockinitstructure;
    NVIC_InitTypeDef NVIC_InitStructure;

    RCC_AHB1PeriphClockCmd(RCC_AHB1Periph_GPIOD, ENABLE); //使能GPIOD时钟
    RCC_APB1PeriphClockCmd(RCC_APB1Periph_USART3, ENABLE); //使能USART3时钟
    USART_DeInit(USART3);  //复位串口3

    GPIO_PinAFConfig(GPIOD, GPIO_PinSource8, GPIO_AF_USART3);
    GPIO_PinAFConfig(GPIOD, GPIO_PinSource9, GPIO_AF_USART3);
    /* D5 USART3_Tx */
    gpio_initstructure.GPIO_Pin = GPIO_Pin_8;
    gpio_initstructure.GPIO_Mode = GPIO_Mode_AF;
    gpio_initstructure.GPIO_OType = GPIO_OType_PP;
    gpio_initstructure.GPIO_Speed = GPIO_Speed_50MHz;
    gpio_initstructure.GPIO_PuPd = GPIO_PuPd_UP;
    GPIO_Init(GPIOD, & gpio_initstructure);

    /* D6 USART3_Rx  */
    gpio_initstructure.GPIO_Pin = GPIO_Pin_9;
    gpio_initstructure.GPIO_Mode = GPIO_Mode_AF;
    //gpio_initstructure.GPIO_OType = GPIO_OType_PP;
    gpio_initstructure.GPIO_Speed = GPIO_Speed_50MHz;
    gpio_initstructure.GPIO_PuPd = GPIO_PuPd_NOPULL;
    GPIO_Init(GPIOD, & gpio_initstructure);

    usart_initstructure.USART_BaudRate = bound;
    usart_initstructure.USART_WordLength = USART_WordLength_8b;
    usart_initstructure.USART_StopBits = USART_StopBits_1;
    usart_initstructure.USART_Parity = USART_Parity_No;
    usart_initstructure.USART_HardwareFlowControl = USART_HardwareFlowControl_None;
    usart_initstructure.USART_Mode = USART_Mode_Rx | USART_Mode_Tx;
    USART_Init(USART3, & usart_initstructure);
    USART_Cmd(USART3, ENABLE);
    USART_ITConfig(USART3, USART_IT_RXNE, ENABLE);

    NVIC_InitStructure.NVIC_IRQChannel = USART3_IRQn;//串口5中断通道
    NVIC_InitStructure.NVIC_IRQChannelPreemptionPriority = 2; //抢占优先级3
    NVIC_InitStructure.NVIC_IRQChannelSubPriority = 3;      //子优先级3
    NVIC_InitStructure.NVIC_IRQChannelCmd = ENABLE;         //IRQ通道使能
    NVIC_Init( & NVIC_InitStructure); //根据指定的参数初始化VIC寄存器、
}

void USART3_SendOneByte(u8 dat)
{
    while((USART3->SR & 0X40) == 0) {};  //循环发送,直到发送完毕
    USART3->DR = (u8) dat;
    while(USART_GetFlagStatus(USART3, USART_FLAG_TC) == RESET);
}

void USART3_SendStr(u8* pucStr, u8 ulNum)
{
    u8 i;
    for(i = 0; i < ulNum; i++)
    {
        USART3_SendOneByte( * pucStr++);
    }
}
